'use strict';
const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');

const page=fs.readFileSync('lab_appearance_windows.html','utf8');
const injector=fs.readFileSync('lab_appearance_inject_windows.go','utf8');
const handler=fs.readFileSync('lab_appearance_windows.go','utf8');
const fallback=fs.readFileSync('lab_appearance_other.go','utf8');
const main=fs.readFileSync('main.go','utf8');
const common=fs.readFileSync('plantilla.html','utf8');
const android=fs.readFileSync('android/app/src/main/assets/index.html','utf8');
const parts=page.split('<!-- LAB_APPEARANCE_SCRIPT -->');
assert.equal(parts.length,2,'La página Apariencia debe separar HTML y JavaScript');
new vm.Script('(()=>{\n'+parts[1]+'\n})();',{filename:'lab_appearance_windows.js'});
assert.match(injector,/\/\/go:build windows/,'Solo Windows recibe Apariencia');
assert.match(handler,/\/\/go:build windows/,'Solo Windows guarda fondos personalizados');
assert.match(fallback,/\/\/go:build !windows/,'Mac y Linux deben seguir sin Apariencia');
assert.match(injector,/if !appIsLab/,'LAB es el único canal con acceso a la pestaña');
assert.match(handler,/if !appIsLab/,'LAB es el único canal con acceso a la API');
assert.match(main,/out = injectLabAppearance\(out\)/,'Inyectar la nueva interfaz en LAB');
assert.match(main,/a\.serveLabAppearance\(w,r\)/,'Conectar los endpoints de Apariencia');
assert.match(injector,/labAppearanceLeave\(\)/,'Las navegaciones internas también han de ocultar Apariencia');
assert.match(page,/id="labAppearanceNav"|id="labAppearanceView"/,'La pantalla ha de tener su propio ID');
for(const id of ['labAppearanceView','labAppearanceChoose','labAppearanceFile','labAppearanceOpacity','labAppearanceBlur','labAppearanceReset','labAppearanceStatus','labAppearancePreview']){
 assert.ok(page.includes('id="'+id+'"'),'Falta el control '+id);
}
for(const theme of ['original','cinema','space','classic'])assert.ok(page.includes('data-lab-theme="'+theme+'"'),'Falta el fondo '+theme);
assert.match(page,/body\.lab-appearance-on::before/,'El fondo debe ocupar la ventana y no los paneles');
assert.match(page,/body\.lab-appearance-on>main/,'El contenido debe quedar encima del fondo');
assert.match(page,/backdrop-filter:blur/,'Los paneles deben permitir translucidez y mantener legibilidad');
assert.match(page,/opacity\/100/,'El regulador de opacidad debe afectar a los paneles');
assert.match(page,/labAppearanceState\.blur/,'Desenfoque ajustable');
assert.match(page,/labAppearanceQueueSave/,'Cambios persistentes');
assert.match(page,/labAppearanceRestore/,'Recuperar apariencia al arrancar');
assert.match(page,/labAppearanceSaveChain/,'Guardar cambios sucesivos en orden');
assert.match(page,/labAppearanceFetchImage/,'Cargar imagen propia desde almacenamiento local');
assert.match(handler,/labWallpaperLimit=12<<20/,'Limitar el tamaño de subida');
assert.match(handler,/image\.DecodeConfig/,'Validar imagen realmente decodificable');
assert.match(handler,/image\/jpeg/,'Aceptar JPEG');
assert.match(handler,/image\/png/,'Aceptar PNG');
assert.match(handler,/apariencia_lab\.json/,'La configuración tiene un archivo LAB independiente');
assert.match(handler,/fondo_personalizado_lab\.bin/,'La imagen tiene un archivo LAB independiente');
assert.match(handler,/a\.auth\(r\)/,'El endpoint debe exigir token local');
assert.ok(!common.includes('labAppearanceNav'),'No editar la plantilla compartida estable');
assert.ok(!android.includes('labAppearanceNav'),'No introducir esta pestaña en Android');
console.log('OK: JS, navegación, seguridad de carga y aislamiento de Apariencia LAB-03');
