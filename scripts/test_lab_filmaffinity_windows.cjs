'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const lab=fs.readFileSync('lab_discover_windows.html','utf8');
const js=lab.split('<!-- LAB_DISCOVERY_SCRIPT -->')[1];
assert.ok(js);
new vm.Script('(()=>{\n'+js+'\n})();');
assert.doesNotMatch(lab,/film\s*affinity/i,'FilmAffinity no debe aparecer en la interfaz');
assert.doesNotMatch(fs.readFileSync('plantilla.html','utf8'),/film\s*affinity/i);
assert.match(js,/labDetailLink\('↗ Ficha de TMDB',m\.tmdb_url\)/);
assert.match(js,/labDetailLink\('▶ Ver tráiler',m\.trailer\)/);
console.log('OK: sin FilmAffinity; TMDB y tráiler conservados');
