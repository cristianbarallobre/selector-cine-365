'use strict';
const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const ui=fs.readFileSync('lab_discover_windows.html','utf8');
const backend=fs.readFileSync('lab_discover_desktop.go','utf8');
const main=fs.readFileSync('main.go','utf8');
const maintenance=fs.readFileSync('lab_maintenance_windows.html','utf8');
const injector=fs.readFileSync('lab_maintenance_desktop.go','utf8');
const original=fs.readFileSync('plantilla.html','utf8');
const code=ui.split('<!-- LAB_DISCOVERY_SCRIPT -->')[1];
const maintJS=maintenance.split('<!-- LAB_MAINTENANCE_SCRIPT -->')[1];
new vm.Script('(()=>{\n'+code+'\n})();',{filename:'lab_discover_windows.html'});
new vm.Script('(()=>{\n'+maintJS+'\n})();',{filename:'lab_maintenance_windows.html'});
assert.match(main,/injectLabMaintenance\(out\)/);
assert.match(main,/\/api\/lab\/maintenance/);
assert.match(injector,/labPreviewRecovery/);
assert.match(backend,/\"language\":\{\"es-ES\"\}/);
assert.match(backend,/\"language\":\{\"es-MX\"\}/);
assert.match(backend,/\"biography_original\":limit\(originalBiography,6500\)/);
assert.ok(!backend.includes('p.Biography=english.Biography'),'El inglés no debe reemplazar el texto español');
assert.match(ui,/id="labPersonOriginal"/);
assert.doesNotMatch(original,/labPersonOriginal/,'La versión estable no debe cambiar');

const elements={labPersonBio:{textContent:''},labPersonOriginal:{hidden:true,onclick:null,textContent:''}};
const ctx={$:id=>{assert.ok(elements[id],id);return elements[id]},Date,Intl,Number,String};
vm.createContext(ctx);
const first=code.indexOf('function labFormatSpanishDate(iso,long=false){');
const end=code.indexOf('async function labOpenPerson(',first);
assert.ok(first>0&&end>first);
vm.runInContext(code.slice(first,end),ctx);
assert.equal(ctx.labFormatSpanishDate('1962-10-11'),'11/10/1962');
assert.equal(ctx.labFormatSpanishDate('1962-10-11',true),'11 de octubre de 1962');
assert.equal(ctx.labFormatSpanishDate('2024-02-29',true),'29 de febrero de 2024');
assert.equal(ctx.labFormatSpanishDate('2023-02-29'),'2023-02-29','No inventar fechas imposibles');
assert.equal(ctx.labFormatSpanishDate(''),'');
assert.equal(vm.runInContext('labPersonDepartmentES.Acting',ctx),'Interpretación');
assert.equal(vm.runInContext('labPersonDepartmentES.Writing',ctx),'Guion');

ctx.labShowPersonBiography({biography:'Biografía en castellano.',biography_original:'English'});
assert.equal(elements.labPersonBio.textContent,'Biografía en castellano.');
assert.equal(elements.labPersonOriginal.hidden,true);
ctx.labShowPersonBiography({biography:'',biography_language:'unavailable',biography_original:'The original in English.'});
assert.match(elements.labPersonBio.textContent,/no dispone de una biografía.*en español/);
assert.equal(elements.labPersonOriginal.hidden,false);
elements.labPersonOriginal.onclick();
assert.equal(elements.labPersonBio.textContent,'The original in English.');
elements.labPersonOriginal.onclick();
assert.match(elements.labPersonBio.textContent,/no dispone de una biografía/);
ctx.labShowPersonBiography({biography:'',biography_original:''});
assert.equal(elements.labPersonOriginal.hidden,true);

assert.match(maintenance,/id="labMaintenanceRefresh"/);
assert.match(maintenance,/id="labMaintenanceClear"/);
assert.match(maintenance,/id="labRecoveryPreview"/);
assert.match(maintJS,/labPreviewRecovery/);
assert.match(maintJS,/Guardado local/);
assert.match(maintJS,/clear_posters/);
assert.match(maintJS,/confirm\(/,'La limpieza manual debe confirmarse');
assert.match(maintenance,/Versiones estables en GitHub/);
console.log('OK: biografías en español, formato de fechas es-ES y mantenimiento seguro solo LAB');
